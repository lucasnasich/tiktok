/** Convierte posición en ranking (1 = mejor) a puntaje 1–10. */
export function rankToScore(rank: number, total: number): number {
  if (total <= 1) return 10;
  return Math.max(1, Math.round(10 - ((rank - 1) * 9) / (total - 1)));
}

export function getMarketRank(
  competitorId: string,
  countryId: string,
): number | undefined {
  const list = MARKET_RANKINGS_BY_COUNTRY[countryId];
  if (!list) return undefined;
  const index = list.indexOf(competitorId);
  return index === -1 ? undefined : index + 1;
}

/** Los 16 mercados Mercantis donde el competidor opera comercialmente. */
export function getCompetitorMercantisMarkets(
  competitorId: string,
): readonly string[] {
  const explicit = getExplicitOperatingCountries(competitorId);
  if (explicit?.length) return explicit;

  return COMPETITOR_FILTER_COUNTRIES.filter((country) =>
    MARKET_RANKINGS_BY_COUNTRY[country]?.includes(competitorId),
  );
}

export function getRankedCountries(): string[] {
  return [...COMPETITOR_FILTER_COUNTRIES];
}
